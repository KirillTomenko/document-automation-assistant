def field_label(path):
    match = re.fullmatch(r"items\[(\d+)\](?:\.(\w+))?", path)
    if match:
        title = f"Позиция {int(match[1]) + 1}"
        return title + (
            " — " + ITEM_FIELDS.get(match[2], "Сведения о работе") if match[2] else ""
        )
    return {
        **LABELS,
        "items": "Перечень работ",
        "documents": "Комплект документов",
    }.get(path, "Сведения документа")


def source_label(location):
    if location.format == "pdf":
        text = "PDF" + (
            f", страница {location.page}" if location.page else ", страница не указана"
        )
        if location.line:
            text += f", строка текста {location.line}"
        if location.column:
            text += f", столбец {location.column}"
        return text
    if location.format == "xlsx":
        return f"Excel, лист {location.sheet}, ячейка {location.cell}"
    parts = ["Word"]
    for name, label in (
        ("section", "раздел"),
        ("paragraph", "абзац"),
        ("table", "таблица"),
        ("row", "строка"),
        ("column", "столбец"),
    ):
        value = getattr(location, name)
        if value is not None:
            parts.append(f"{label} {value}")
    return ", ".join(parts)
